CREATE PROCEDURE BANK.RECORD_PAYMENT(IN P_ACCOUNT INT, IN P_AMOUNT DECIMAL(12,2))
LANGUAGE SQL
BEGIN ATOMIC
  DECLARE V INT DEFAULT 0;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
    SIGNAL SQLSTATE '75000' SET MESSAGE_TEXT = 'payment failed';
  PAYMENT_LOOP: FOR V AS PAYMENT_CURSOR CURSOR FOR SELECT ID FROM BANK.ACCOUNT DO
    INSERT INTO BANK.PAYMENT (ACCOUNT_ID, AMOUNT) VALUES (V, P_AMOUNT);
  END FOR PAYMENT_LOOP;
  INSERT INTO BANK.AUDIT_LOG (EVENT_NAME) VALUES ('payment');
END@
CREATE PROCEDURE BANK.UPDATE_BALANCE(IN P_ACCOUNT INT)
LANGUAGE SQL
BEGIN
  UPDATE BANK.ACCOUNT SET BALANCE = BALANCE + 1 WHERE ID = P_ACCOUNT;
END@
CREATE PROCEDURE BANK.TRANSFER_FUNDS(IN P_SOURCE INT, IN P_TARGET INT)
LANGUAGE SQL
BEGIN
  INSERT INTO BANK.TRANSFER (SOURCE_ACCOUNT, TARGET_ACCOUNT) VALUES (P_SOURCE, P_TARGET);
END@
CREATE FUNCTION BANK.ACCOUNT_COUNT() RETURNS INT LANGUAGE SQL
BEGIN ATOMIC
  RETURN SELECT COUNT(*) FROM BANK.ACCOUNT;
END@
CREATE FUNCTION BANK.CURRENT_BALANCE(IN P_ACCOUNT INT) RETURNS DECIMAL(12,2) LANGUAGE SQL
BEGIN ATOMIC
  RETURN SELECT BALANCE FROM BANK.ACCOUNT WHERE ID = P_ACCOUNT;
END@
CREATE PROCEDURE BANK.PREPARED(IN P_ID INT)
LANGUAGE SQL
BEGIN
  PREPARE S1 FROM 'SELECT ID FROM BANK.ACCOUNT WHERE ID = ?';
  EXECUTE S1 USING P_ID;
END@
