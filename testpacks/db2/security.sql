CREATE SEQUENCE BANK.ACCOUNT_SEQ AS BIGINT START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE PUBLIC ALIAS BANK.CUSTOMER_ALIAS FOR TABLE BANK.CUSTOMER;
CREATE SYNONYM BANK.CUSTOMER_SYNONYM FOR BANK.CUSTOMER;
CREATE PERMISSION BANK.CUSTOMER_PERMISSION ON BANK.CUSTOMER AS C FOR ROWS WHERE C.STATUS = 'A' ENABLE;
CREATE MASK BANK.CUSTOMER_MASK ON BANK.CUSTOMER AS C FOR COLUMN NAME RETURN CASE WHEN C.ID = 1 THEN 'x' ELSE NAME END ENABLE;
CREATE INDEX BANK.ACCOUNT_INDEX ON BANK.ACCOUNT (CUSTOMER_ID ASC) ALLOW REVERSE SCANS;
GRANT SELECT, UPDATE ON TABLE BANK.ACCOUNT TO ROLE REPORTER WITH GRANT OPTION;
GRANT EXECUTE ON PROCEDURE BANK.RECORD_PAYMENT TO ROLE APP;
REVOKE UPDATE ON TABLE BANK.ACCOUNT FROM ROLE REPORTER;
