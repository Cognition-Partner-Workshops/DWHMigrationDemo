CREATE TABLE BANK.CUSTOMER (ID INT NOT NULL, NAME VARCHAR(80), STATUS CHAR(1)) ORGANIZE BY COLUMN IN BANK_TS;
CREATE TABLE BANK.ACCOUNT (ID INT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1), CUSTOMER_ID INT REFERENCES BANK.CUSTOMER(ID), BALANCE DECIMAL(12,2)) DISTRIBUTE BY HASH (ID) ORGANIZE BY ROW IN BANK_TS;
CREATE TABLE BANK.ACCOUNT_HISTORY (ID INT, ACCOUNT_ID INT, CHANGED_AT TIMESTAMP) IN BANK_TS;
CREATE TABLE BANK.BRANCH (ID INT NOT NULL, NAME VARCHAR(80)) ORGANIZE BY ROW;
CREATE TABLE BANK.PRODUCT (ID INT NOT NULL, NAME VARCHAR(80));
CREATE TABLE BANK.ACCOUNT_PRODUCT (ACCOUNT_ID INT, PRODUCT_ID INT REFERENCES BANK.PRODUCT(ID));
CREATE TABLE BANK.PAYMENT (ID INT, ACCOUNT_ID INT REFERENCES BANK.ACCOUNT(ID), AMOUNT DECIMAL(12,2));
CREATE TABLE BANK.TRANSFER (ID INT, SOURCE_ACCOUNT INT REFERENCES BANK.ACCOUNT(ID), TARGET_ACCOUNT INT REFERENCES BANK.ACCOUNT(ID));
CREATE TABLE BANK.AUDIT_LOG (ID INT, EVENT_NAME VARCHAR(80));
CREATE TABLE BANK.DAILY_BALANCE (ACCOUNT_ID INT, BALANCE DECIMAL(12,2));
CREATE TABLE BANK.EVENT_LOG (ID INT, EVENT_TIME TIMESTAMP);
CREATE TABLE BANK.HISTORY (ID INT, VALID_FROM TIMESTAMP GENERATED ALWAYS AS ROW BEGIN, VALID_TO TIMESTAMP GENERATED ALWAYS AS ROW END, PERIOD SYSTEM_TIME (VALID_FROM, VALID_TO)) IN BANK_TS;
CREATE TABLE BANK.HISTORY_ARCHIVE (ID INT, VALID_FROM TIMESTAMP, VALID_TO TIMESTAMP, PERIOD SYSTEM_TIME (VALID_FROM, VALID_TO));
ALTER TABLE BANK.HISTORY ADD VERSIONING USE HISTORY TABLE BANK.HISTORY_ARCHIVE;
CREATE TABLE BANK.ACCOUNT_MQT AS (SELECT ID, BALANCE FROM BANK.ACCOUNT) DATA INITIALLY DEFERRED REFRESH DEFERRED ENABLE QUERY OPTIMIZATION;
CREATE TABLE BANK.RECONCILIATION (ID INT, ACCOUNT_ID INT REFERENCES BANK.ACCOUNT(ID));
CREATE TABLE BANK.SETTLEMENT (ID INT, PAYMENT_ID INT REFERENCES BANK.PAYMENT(ID));
