CREATE VIEW BANK.CUSTOMER_VIEW AS SELECT ID, NAME FROM BANK.CUSTOMER;
CREATE VIEW BANK.ACCOUNT_VIEW AS SELECT A.ID, A.BALANCE FROM BANK.ACCOUNT A;
CREATE VIEW BANK.PAYMENT_VIEW AS SELECT P.ID, P.AMOUNT FROM BANK.PAYMENT P;
CREATE VIEW BANK.TRANSFER_VIEW AS SELECT ID, SOURCE_ACCOUNT, TARGET_ACCOUNT FROM BANK.TRANSFER;
CREATE VIEW BANK.ACTIVE_CUSTOMER AS SELECT ID, NAME FROM BANK.CUSTOMER WHERE STATUS = 'A';
CREATE VIEW BANK.ACCOUNT_TOTALS AS SELECT ACCOUNT_ID, SUM(AMOUNT) AS TOTAL FROM BANK.PAYMENT GROUP BY ACCOUNT_ID;
CREATE VIEW BANK.BRANCH_VIEW AS SELECT ID, NAME FROM BANK.BRANCH;
CREATE VIEW BANK.PRODUCT_VIEW AS SELECT ID, NAME FROM BANK.PRODUCT;
CREATE VIEW BANK.EXTERNAL_CUSTOMER AS SELECT ID FROM EXTDB.REMOTE.CUSTOMER;
CREATE VIEW BANK.SETTLEMENT_VIEW AS SELECT ID, PAYMENT_ID FROM BANK.SETTLEMENT;
CREATE VIEW BANK.RECENT_ACCOUNTS AS SELECT ID, BALANCE FROM BANK.ACCOUNT FETCH FIRST 10 ROWS ONLY;
CREATE VIEW BANK.UNCOMMITTED_CUSTOMERS AS SELECT ID, NAME FROM BANK.CUSTOMER FETCH FIRST 100 ROWS ONLY WITH UR;
SELECT ID FROM BANK.CUSTOMER FOR SYSTEM_TIME AS OF CURRENT_TIMESTAMP;
