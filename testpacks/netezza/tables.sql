CREATE TABLE LOGISTICS.CUSTOMER (ID INT, NAME VARCHAR(80), REGION VARCHAR(20)) DISTRIBUTE ON (ID) ORGANIZE ON (REGION);
CREATE TABLE LOGISTICS.ADDRESS (ID INT, CUSTOMER_ID INT, CITY VARCHAR(40));
CREATE TABLE LOGISTICS.CARRIER (ID INT, NAME VARCHAR(80));
CREATE TABLE LOGISTICS.ROUTE (ID INT, ORIGIN VARCHAR(40), DESTINATION VARCHAR(40));
CREATE TABLE LOGISTICS.WAREHOUSE (ID INT, CITY VARCHAR(40)) DISTRIBUTE ON RANDOM;
CREATE TABLE LOGISTICS.PRODUCT (ID INT, DESCRIPTION VARCHAR(120));
CREATE TABLE LOGISTICS.INVENTORY (PRODUCT_ID INT, WAREHOUSE_ID INT, QUANTITY INT);
CREATE TABLE LOGISTICS.ORDER_HEADER (ID INT, CUSTOMER_ID INT, CREATED_AT TIMESTAMP);
CREATE TABLE LOGISTICS.ORDER_LINE (ID INT, ORDER_ID INT, PRODUCT_ID INT, QUANTITY INT);
CREATE TABLE LOGISTICS.SHIPMENT (ID INT, ORDER_ID INT, CUSTOMER_ID INT, CARRIER_ID INT, STATUS VARCHAR(20));
CREATE TABLE LOGISTICS.SHIPMENT_EVENT (ID INT, SHIPMENT_ID INT, EVENT_TIME TIMESTAMP, STATUS VARCHAR(20));
CREATE TABLE LOGISTICS.DRIVER (ID INT, NAME VARCHAR(80));
CREATE TABLE LOGISTICS.VEHICLE (ID INT, DRIVER_ID INT, PLATE VARCHAR(20));
CREATE TABLE LOGISTICS.DELIVERY (ID INT, SHIPMENT_ID INT, DRIVER_ID INT);
CREATE TABLE LOGISTICS.DELIVERY_ATTEMPT (ID INT, DELIVERY_ID INT, ATTEMPT_TIME TIMESTAMP);
CREATE TABLE LOGISTICS.TRACKING (ID INT, SHIPMENT_ID INT, LOCATION VARCHAR(80));
CREATE TABLE LOGISTICS.FREIGHT (ID INT, SHIPMENT_ID INT, AMOUNT DECIMAL(10,2));
CREATE TABLE LOGISTICS.RETURN_ORDER (ID INT, SHIPMENT_ID INT, REASON VARCHAR(80));
CREATE EXTERNAL TABLE LOGISTICS.SHIPMENT_STAGE (ID INT, STATUS VARCHAR(20))
USING (DATAOBJECT ('/loads/shipments.csv') DELIMITER '|' SKIPROWS 1 REMOTESOURCE 'ODBC');
CREATE TABLE LOGISTICS.RECONCILIATION AS SELECT ID, STATUS FROM LOGISTICS.SHIPMENT DISTRIBUTE ON (ID);
