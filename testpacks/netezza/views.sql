CREATE VIEW LOGISTICS.CUSTOMER_VIEW AS SELECT ID, NAME FROM LOGISTICS.CUSTOMER;
CREATE VIEW LOGISTICS.ACTIVE_SHIPMENTS AS SELECT ID, STATUS FROM LOGISTICS.SHIPMENT WHERE STATUS = 'active';
CREATE VIEW LOGISTICS.ORDER_DETAIL AS SELECT O.ID, L.PRODUCT_ID FROM LOGISTICS.ORDER_HEADER O JOIN LOGISTICS.ORDER_LINE L ON O.ID = L.ORDER_ID;
CREATE VIEW LOGISTICS.SHIPMENT_HISTORY AS SELECT SHIPMENT_ID, STATUS FROM LOGISTICS.SHIPMENT_EVENT;
CREATE VIEW LOGISTICS.DELIVERY_VIEW AS SELECT ID, SHIPMENT_ID FROM LOGISTICS.DELIVERY;
CREATE VIEW LOGISTICS.CARRIER_VIEW AS SELECT ID, NAME FROM LOGISTICS.CARRIER;
CREATE VIEW LOGISTICS.INVENTORY_VIEW AS SELECT PRODUCT_ID, QUANTITY FROM LOGISTICS.INVENTORY;
CREATE VIEW LOGISTICS.EXTERNAL_CUSTOMER AS SELECT ID FROM ERP.REMOTE.CUSTOMER;
CREATE VIEW LOGISTICS.RECENT_SHIPMENTS AS SELECT ID FROM LOGISTICS.SHIPMENT ORDER BY ID;
CREATE MATERIALIZED VIEW LOGISTICS.SHIPMENT_SUMMARY AS SELECT STATUS, COUNT(*) AS TOTAL FROM LOGISTICS.SHIPMENT GROUP BY STATUS;
CREATE VIEW LOGISTICS.STAGED_SHIPMENTS AS SELECT ID, STATUS FROM LOGISTICS.SHIPMENT_STAGE;
